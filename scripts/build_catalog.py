"""Build every generated artefact from its sources.

Sources of truth:   patterns/*/pattern.toml, patterns/guide.toml, research/sources.toml, experiments/results/*.json
Generated:          patterns/*/README.md, patterns/README.md, docs/decision-guide.md, research/SOURCES.md,
                    reference links and live numbers inside hand-written Markdown, explorer/public/data/*

    python scripts/build_catalog.py           # write
    python scripts/build_catalog.py --check   # exit 1 if anything is stale (used by tests and CI)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

RESULTS = ROOT / "experiments" / "results"
DATA = ROOT / "explorer" / "public" / "data"
LIVE_MD = ["README.md", "AGENTS.md", "research/topics.md", "research/frameworks.md", "research/README.md", "docs/methodology.md", "docs/integration.md", "docs/limitations.md", "docs/roadmap.md", "docs/engineering-decisions.md", "docs/extending.md"]
GENERATED_NOTE = "<!-- Generated by scripts/build_catalog.py. Edit {src} instead. -->"


class BuildError(Exception):
    pass


# -- loading ------------------------------------------------------------------------
def load_results() -> dict[str, dict]:
    manifest = json.loads((RESULTS / "manifest.json").read_text())
    return {rid: json.loads((RESULTS / f"{rid}.json").read_text()) for rid in manifest["experiments"]}


def load_sources() -> list[dict]:
    return tomllib.loads((ROOT / "research" / "sources.toml").read_text())["source"]


def load_patterns() -> list[dict]:
    pats = [tomllib.loads(p.read_text()) for p in sorted((ROOT / "patterns").glob("*/pattern.toml"))]
    return sorted(pats, key=lambda p: p["order"])


# -- live numbers -------------------------------------------------------------------
def lookup(results: dict[str, dict], spec: str) -> str:
    parts = spec.split("|")
    if len(parts) != 5:
        raise BuildError(f"bad number reference: {spec}")
    exp, scenario, arch, key, fmt = parts
    if exp not in results:
        raise BuildError(f"unknown experiment in {spec}")
    rows = [r for r in results[exp]["rows"] if r["arch"] == arch and (scenario == "*" or r["scenario"] == scenario)]
    if not rows or key not in rows[0]:
        raise BuildError(f"no result row/key for {spec}")
    v = rows[0][key]
    if fmt == "%":
        return f"{v:.0%}"
    if fmt == "k":
        return f"{v / 1000:.1f}k" if v >= 1000 else f"{v:.0f}"
    if fmt == "s":
        return f"{v / 1000:.1f}"
    if fmt in "0123":
        return f"{v:,.{int(fmt)}f}"
    raise BuildError(f"unknown format in {spec}")


def resolve(obj: Any, results: dict[str, dict]) -> Any:
    if isinstance(obj, str):
        return re.sub(r"\{\{([^}]+)\}\}", lambda m: lookup(results, m.group(1)), obj)
    if isinstance(obj, list):
        return [resolve(v, results) for v in obj]
    if isinstance(obj, dict):
        return {k: resolve(v, results) for k, v in obj.items()}
    return obj


def refresh_markdown(text: str, results: dict[str, dict], sources: list[dict]) -> str:
    """Refresh `<!--n:spec-->value<!--/n-->` numbers and the reference-link block."""
    text = re.sub(r"<!--n:([^>]+?)-->.*?<!--/n-->", lambda m: f"<!--n:{m.group(1)}-->{lookup(results, m.group(1))}<!--/n-->", text)
    by_key = {s["key"]: s for s in sources}
    prose = re.sub(r"```.*?```|`[^`\n]*`", "", text, flags=re.S)  # code spans may show the syntax itself
    used = sorted({k for k in re.findall(r"\]\[([a-z0-9-]+)\]", prose)})
    unknown = [k for k in used if k not in by_key]
    if unknown:
        raise BuildError(f"citation keys not in research/sources.toml: {unknown}")
    text = re.sub(r"\n*<!-- refs:start -->.*?<!-- refs:end -->\n*", "\n", text, flags=re.S).rstrip() + "\n"
    if used:
        text += "\n<!-- refs:start -->\n" + "\n".join(f'[{k}]: {by_key[k]["url"]} "{by_key[k]["title"].replace(chr(34), chr(39))}"' for k in used) + "\n<!-- refs:end -->\n"
    return text


# -- rendering ----------------------------------------------------------------------
def fmt_cell(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.2f}" if abs(v) < 100 else f"{v:,.0f}"
    if isinstance(v, int) and not isinstance(v, bool):
        return f"{v:,}"
    return str(v)


def results_tables(exp: dict, only_arch: set[str] | None = None) -> list[str]:
    out: list[str] = []
    groups: dict[str, list[dict]] = {}
    for row in exp["rows"]:
        groups.setdefault(" / ".join(str(row[g]) for g in exp["group_by"]), []).append(row)
    for g, rows in groups.items():
        cols = [c for c in exp["columns"] if any(c["key"] in r for r in rows)]
        out += [f"**{g}**", "", "| " + " | ".join(c["label"] for c in cols) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(cols))) + "|"]
        for r in rows:
            cells = []
            for c in cols:
                v = r.get(c["key"], "")
                if c["key"] == "success_rate":
                    v = f"{v:.1%}"
                elif c["key"] in ("exfil_mean", "replay_identical"):
                    v = f"{v:.0%}"
                cells.append(fmt_cell(v))
            out.append("| " + " | ".join(cells) + " |")
        out.append("")
    return out


def bullets(items: list[str]) -> list[str]:
    return [f"- {i}" for i in items]


def pattern_readme(p: dict, exp: dict, sources: dict[str, dict]) -> str:
    L = [GENERATED_NOTE.format(src=f"patterns/{p['id']}/pattern.toml"), "", f"# {p['title']}", "", f"> {p['tagline']}", "", "## Problem", "", p["problem"].strip(), "", "**Practical applications**", "", *bullets(p["applications"]), "",
         "## Recommendation", "", "_This section is advice. The evidence behind it is under [Measured comparison](#measured-comparison)._", "", p["decision"].strip(), "", "## Solutions at a glance", "",
         "| Solution | Status | Implementation | Example | Tests |", "|---|---|---|---|---|"]
    link = lambda path: f"[`{path}`](../../{path})" if path else "-"
    for s in p["solutions"]:
        L.append(f"| [{s['name']}](#{anchor(s['name'])}) | {s['status']} | {link(s.get('implementation', ''))} | {link(s.get('example', ''))} | {link(s.get('tests', ''))} |")
    L.append("")
    for s in p["solutions"]:
        L += [f"## {s['name']}", "", f"**Status:** {s['status']}" + ("" if s["status"] == "implemented" else " (described for comparison; not implemented in this repository)"), "", s["summary"], ""]
        if s.get("diagram"):
            L += ["```mermaid", s["diagram"].strip(), "```", ""]
        L += ["**Advantages**", "", *bullets(s["advantages"]), "", "**Limitations**", "", *bullets(s["limitations"]), ""]
        for key, label in (("performance", "Performance"), ("complexity", "Complexity"), ("reliability", "Reliability"), ("security", "Security")):
            if s.get(key):
                L += [f"**{label}.** {s[key]}", ""]
        L += ["**Use when**", "", *bullets(s["use_when"]), "", "**Avoid when**", "", *bullets(s["avoid_when"]), ""]
        if s.get("integration"):
            L += ["**Integration**", "", s["integration"].strip(), ""]
        L += [f"**Where you have seen it.** {s['frameworks']}", ""]
    L += ["## Measured comparison", "", f"From [`experiments/results/{exp['id']}.json`](../../experiments/results/{exp['id']}.json), produced by `python -m experiments.run_all`. **Question:** {exp['question']}", "",
          *results_tables(exp), "**Measured findings**", "", *bullets(exp["findings"]), "", "**Limitations of this experiment**", "", *bullets(exp["limitations"]), "", "## Research", ""]
    for key in p["research"]:
        s = sources[key]
        L.append(f"- {s['authors']} ({s['year']}). [{s['title']}]({s['url']}).")
    return "\n".join(L) + "\n"


def anchor(name: str) -> str:
    return re.sub(r"[^a-z0-9 -]", "", name.lower()).replace(" ", "-")


def patterns_index(pats: list[dict]) -> str:
    L = [GENERATED_NOTE.format(src="patterns/*/pattern.toml"), "", "# Pattern catalogue", "", "Each entry states a problem, at least three solutions, diagrams, tested implementations, measured comparisons and integration notes.", "",
         "| Problem | Solutions (implemented unless marked) | Experiment |", "|---|---|---|"]
    for p in pats:
        sols = ", ".join(s["name"] + ("" if s["status"] == "implemented" else " _(documented)_") for s in p["solutions"])
        L.append(f"| [{p['title']}]({p['id']}/README.md) | {sols} | [`{p['experiment']}`](../experiments/results/{p['experiment']}.json) |")
    L += ["", "## Comparison across all implemented solutions", "", "| Problem | Solution | One-line summary | Use when | Avoid when |", "|---|---|---|---|---|"]
    for p in pats:
        for s in p["solutions"]:
            if s["status"] == "implemented":
                L.append(f"| {p['title']} | [{s['name']}]({p['id']}/README.md#{anchor(s['name'])}) | {s['summary']} | {s['use_when'][0]} | {s['avoid_when'][0]} |")
    L += ["", "To add an entry see [`docs/extending.md`](../docs/extending.md)."]
    return "\n".join(L) + "\n"


def decision_guide(entries: list[dict], pats: dict[str, dict]) -> str:
    L = [GENERATED_NOTE.format(src="patterns/guide.toml"), "", "# Decision guide", "", "Find your problem, read the recommendation, check the evidence.", "",
         "- **Recommendation** is engineering advice from the authors.", "- **Measured here** is a result from this repository's simulator; conditions and limitations are in [`experiments/RESULTS.md`](../experiments/RESULTS.md) and [`methodology.md`](methodology.md).", ""]
    for e in entries:
        p = pats[e["pattern"]]
        s = next(x for x in p["solutions"] if x["id"] == e["solution"])
        L += [f"## {e['problem']}", "", f"**Recommendation.** {e['recommendation']}", "", f"**Measured here.** {e['evidence']}", "",
              f"**Pattern.** [{p['title']}](../patterns/{p['id']}/README.md) / [{s['name']}](../patterns/{p['id']}/README.md#{anchor(s['name'])})" + (f" / code: [`{s['implementation']}`](../{s['implementation']})" if s.get("implementation") else ""), ""]
    return "\n".join(L)


def sources_md(sources: list[dict]) -> str:
    L = [GENERATED_NOTE.format(src="research/sources.toml"), "", "# Sources", "", "`verified` = how the entry was checked on the date in [`verification.json`](verification.json): **content** (page fetched and the cited claim read), **reachable** (URL resolved), **unverified** (could not be fetched automatically).", "",
         "| Key | Kind | Source | Verified | What it is cited for |", "|---|---|---|---|---|"]
    for s in sources:
        L.append(f"| `{s['key']}` | {s['kind']} | {s['authors']} ({s['year']}). [{s['title']}]({s['url']}) | {s['verified']} | {s['note']} |")
    return "\n".join(L) + "\n"


# -- build --------------------------------------------------------------------------
def build() -> dict[Path, str]:
    results = load_results()
    sources = load_sources()
    by_key = {s["key"]: s for s in sources}
    raw = load_patterns()
    files: dict[Path, str] = {}
    code: dict[str, str] = {}
    pats = []
    for p in raw:
        p = resolve(p, results)
        if p["experiment"] not in results:
            raise BuildError(f"{p['id']}: unknown experiment {p['experiment']}")
        archs = {r["arch"] for r in results[p["experiment"]]["rows"]}
        for key in p["research"]:
            if key not in by_key:
                raise BuildError(f"{p['id']}: unknown source {key}")
        for s in p["solutions"]:
            for field in ("implementation", "example", "tests"):
                if s.get(field):
                    f = ROOT / s[field]
                    if not f.exists():
                        raise BuildError(f"{p['id']}/{s['id']}: missing {s[field]}")
                    if field != "tests":
                        code[s[field]] = f.read_text()
            if s["status"] == "implemented" and not all(s.get(f) for f in ("implementation", "example", "tests")):
                raise BuildError(f"{p['id']}/{s['id']}: implemented solutions need implementation, example and tests")
            for a in s.get("result_arch", []):
                if a not in archs:
                    raise BuildError(f"{p['id']}/{s['id']}: result_arch {a!r} not in experiment {p['experiment']}")
        pats.append(p)
        files[ROOT / "patterns" / p["id"] / "README.md"] = pattern_readme(p, results[p["experiment"]], by_key)
    files[ROOT / "patterns" / "README.md"] = patterns_index(pats)
    guide = resolve(tomllib.loads((ROOT / "patterns" / "guide.toml").read_text())["entry"], results)
    pat_by_id = {p["id"]: p for p in pats}
    for e in guide:
        if e["pattern"] not in pat_by_id or e["solution"] not in [s["id"] for s in pat_by_id[e["pattern"]]["solutions"]]:
            raise BuildError(f"guide entry points at unknown pattern/solution: {e['pattern']}/{e['solution']}")
    files[ROOT / "docs" / "decision-guide.md"] = decision_guide(guide, pat_by_id) + "\n"
    files[ROOT / "research" / "SOURCES.md"] = sources_md(sources)
    for rel in LIVE_MD:
        f = ROOT / rel
        if f.exists():
            files[f] = refresh_markdown(f.read_text(), results, sources)

    from record_traces import record_all

    manifest = json.loads((RESULTS / "manifest.json").read_text())
    perf = json.loads((RESULTS / "perf.json").read_text()) if (RESULTS / "perf.json").exists() else None
    verification = ROOT / "research" / "verification.json"
    traces = record_all()
    dump = lambda o: json.dumps(o, indent=1, sort_keys=True) + "\n"
    files[DATA / "catalog.json"] = dump({"patterns": pats, "guide": guide, "code": code, "sources": sources, "manifest": manifest,
                                         "verification": json.loads(verification.read_text()) if verification.exists() else None,
                                         "traces": [{k: v for k, v in t.items() if k != "events"} | {"events": len(t["events"])} for t in traces]})
    files[DATA / "results.json"] = dump({"experiments": results, "perf": perf})
    for t in traces:
        files[DATA / "traces" / f"{t['id']}.json"] = dump(t)
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    try:
        files = build()
    except BuildError as e:
        print(f"build error: {e}", file=sys.stderr)
        return 2
    stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p])
        print(f"wrote {p.relative_to(ROOT)}")
    print(f"{len(files)} artefacts, {len(stale)} updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
