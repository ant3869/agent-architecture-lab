"""Run every experiment and write results.

    python -m experiments.run_all            # full run (n=200), rewrites experiments/results and RESULTS.md
    python -m experiments.run_all --n 40     # quick run, prints a digest, writes nothing unless --write
    python -m experiments.run_all --perf     # also record machine-dependent timing to results/perf.json
"""
from __future__ import annotations

import argparse
import hashlib
import json
import platform
import sys
import time
import tracemalloc
from pathlib import Path

from . import exp_complexity, exp_durability, exp_loops, exp_memory, exp_orchestration, exp_permissions, exp_recovery, exp_routing, exp_tools, exp_tracing

EXPERIMENTS = [exp_loops, exp_orchestration, exp_durability, exp_recovery, exp_memory, exp_routing, exp_tools, exp_permissions, exp_tracing, exp_complexity]
OUT = Path(__file__).resolve().parent / "results"


def run_all(n: int) -> dict[str, dict]:
    return {r["id"]: r for r in (m.run(n) for m in EXPERIMENTS)}


def digest(results: dict[str, dict]) -> str:
    return hashlib.sha256(json.dumps(results, sort_keys=True).encode()).hexdigest()


def fmt(v) -> str:
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        return f"{v:.2f}" if abs(v) < 100 else f"{v:,.0f}"
    if isinstance(v, int):
        return f"{v:,}"
    return str(v)


def markdown(results: dict[str, dict], n: int, sha: str) -> str:
    out = [
        "# Measured results",
        "",
        "> Generated by `python -m experiments.run_all`. Do not edit by hand.",
        f"> n = {n}, digest `{sha[:16]}`. Re-running with the same n must reproduce this digest (see `tests/test_experiments.py`).",
        "",
        "Everything on this page is **measured** by executing the reference implementations against the deterministic simulator.",
        "The simulator's assumptions are listed under each experiment and in `docs/methodology.md`. Recommendations live in `docs/decision-guide.md`, not here.",
        "",
    ]
    for r in results.values():
        out += [f"## {r['title']}", "", f"**Question.** {r['question']}", "", "**Conditions.** `" + json.dumps(r["conditions"], sort_keys=True) + "`", ""]
        groups: dict[str, list[dict]] = {}
        for row in r["rows"]:
            groups.setdefault(" / ".join(str(row[g]) for g in r["group_by"]), []).append(row)
        for g, rows in groups.items():
            cols = [c for c in r["columns"] if any(c["key"] in row for row in rows)]
            out += [f"### {g}", "", "| " + " | ".join(c["label"] for c in cols) + " |", "|" + "|".join("---" if i == 0 else "---:" for i, _ in enumerate(cols)) + "|"]
            for row in rows:
                cells = []
                for c in cols:
                    v = row.get(c["key"], "")
                    if c["key"] == "success_rate":
                        lo, hi = row["success_ci95"]
                        v = f"{v:.1%} [{lo:.0%}-{hi:.0%}]"
                    elif c["key"] in ("exfil_mean", "replay_identical"):
                        v = f"{v:.0%}"
                    cells.append(fmt(v))
                out.append("| " + " | ".join(cells) + " |")
            out.append("")
        out += ["**Measured findings**", ""] + [f"- {f}" for f in r["findings"]] + ["", "**Limitations of this experiment**", ""] + [f"- {x}" for x in r["limitations"]] + [""]
    return "\n".join(out)


def perf() -> dict:
    """Machine-dependent numbers. Kept out of the reproducibility digest."""
    from agentlab.eval.harness import run_loop
    from agentlab.sim.tasks import make_suite

    from .exp_orchestration import run_orch

    tasks = make_suite(50, stages=4, lookups=3)
    rows = []
    cases = {name: (lambda t, name=name: run_loop(name, t)) for name in ("react", "plan_execute", "verified_graph")}
    cases["supervisor"] = lambda t: run_orch("supervisor", t)
    cases["handoff"] = lambda t: run_orch("handoff", t)
    for name, fn in cases.items():
        t0 = time.perf_counter()
        for t in tasks:
            fn(t)
        wall = (time.perf_counter() - t0) / len(tasks)
        tracemalloc.start()
        fn(tasks[0])
        _, peak = tracemalloc.get_traced_memory()
        tracemalloc.stop()
        rows.append({"arch": name, "wall_ms_per_run": round(wall * 1000, 3), "peak_alloc_kb": round(peak / 1024, 1)})
    return {"note": "Harness overhead on this machine for 29-step tasks; excludes all simulated latency. Not reproducible across machines.", "python": sys.version.split()[0], "platform": f"{platform.system()} {platform.machine()}", "rows": rows}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--write", action="store_true", help="write results even when n != 200")
    ap.add_argument("--perf", action="store_true")
    args = ap.parse_args()
    t0 = time.perf_counter()
    results = run_all(args.n)
    sha = digest(results)
    print(f"n={args.n} digest={sha[:16]} elapsed={time.perf_counter() - t0:.1f}s")
    for r in results.values():
        print(f"\n== {r['title']}")
        for f in r["findings"]:
            print("  -", f)
    if args.n == 200 or args.write:
        OUT.mkdir(exist_ok=True)
        for rid, r in results.items():
            (OUT / f"{rid}.json").write_text(json.dumps(r, indent=1, sort_keys=True) + "\n")
        (OUT / "manifest.json").write_text(json.dumps({"n": args.n, "digest": sha, "experiments": list(results)}, indent=1) + "\n")
        (OUT.parent / "RESULTS.md").write_text(markdown(results, args.n, sha))
        print(f"\nwrote {OUT} and RESULTS.md")
    if args.perf:
        OUT.mkdir(exist_ok=True)
        p = perf()
        (OUT / "perf.json").write_text(json.dumps(p, indent=1) + "\n")
        print(json.dumps(p["rows"], indent=1))


if __name__ == "__main__":
    main()
